"""The boundary's message types as TypeScript, generated from `api.values` (#306).

The browser client (#292, decision 6) reads the same JSON `api.wire` writes. **No message shape is
written down twice** (the rule #36 set for the codec), so the client's types are not written at
all: this module reads each dataclass the wire carries and prints its TypeScript form. A field
added to a value appears in the client's types the next time this runs, and CI fails while the
committed file is stale (`tests/api/test_typescript.py`), so a client reading a field the server
no longer sends fails to compile instead of drawing `undefined`.

What it prints is the **wire** form, not the Python one: every object carries its `"$type"` tag,
a tuple is an array, and a `Column`'s bytes are the base64 string `api.wire` encodes them as.
Decoding that string into a typed array is the client's one piece of wire logic
(`clients/web/src/api/wire.ts`).

    python -m api.typescript            print the file
    python -m api.typescript --write    rewrite clients/web/src/api/values.ts
"""

from __future__ import annotations

import argparse
import dataclasses
import types
import typing
from pathlib import Path
from typing import Any, Union

from api import values
from api.wire import _TYPES

TARGET = Path(__file__).resolve().parents[1] / "clients" / "web" / "src" / "api" / "values.ts"

_HEADER = """\
// Generated by `python -m api.typescript --write` from api/values.py. Do not edit by hand:
// CI regenerates this file and fails if it differs (tests/api/test_typescript.py).
//
// These are the wire forms api.wire writes: every object is tagged with "$type", tuples are
// arrays, and a Column's bytes are base64 text (decoded by ./wire.ts).
"""

_COLUMN = """\
export interface Column {
  readonly $type: "Column";
  /** A NumPy dtype string, always little-endian or byte-order free: "<f4", "<i8", "|b1". */
  readonly dtype: string;
  readonly shape: readonly number[];
  /** The elements, C-contiguous, as base64. */
  readonly data: string;
}
"""

_PRIMITIVES: dict[Any, str] = {
    int: "number",
    float: "number",
    str: "string",
    bool: "boolean",
    type(None): "null",
}


def typescript_type(hint: Any) -> str:
    """The TypeScript spelling of one resolved field annotation. Raises on anything the wire
    cannot carry, because a type printed as `any` would be the silent gap this module closes."""
    if hint in _PRIMITIVES:
        return _PRIMITIVES[hint]
    if hint is values.Column:
        return "Column"
    if isinstance(hint, type) and _TYPES.get(hint.__name__) is hint:
        return hint.__name__
    origin = typing.get_origin(hint)
    arguments = typing.get_args(hint)
    if origin in (Union, types.UnionType):
        return " | ".join(typescript_type(argument) for argument in arguments)
    if origin is tuple:
        if len(arguments) == 2 and arguments[1] is Ellipsis:
            return f"readonly {_bracketed(typescript_type(arguments[0]))}[]"
        return "readonly [" + ", ".join(typescript_type(argument) for argument in arguments) + "]"
    raise TypeError(f"the wire carries no TypeScript form for {hint!r}")


def _bracketed(spelling: str) -> str:
    """`a | b` as an array element needs parentheses, or `[]` binds to `b` alone."""
    return f"({spelling})" if " | " in spelling else spelling


def _interface(cls: type) -> str:
    # The carried types (`Progress`, `Record`, `Sample`) live in modules that import their
    # neighbours only for type checking, so names are resolved against `api.values`, which holds
    # every type the wire carries.
    hints = typing.get_type_hints(cls, localns=vars(values))
    lines = [f"export interface {cls.__name__} {{", f'  readonly $type: "{cls.__name__}";']
    for field in dataclasses.fields(cls):
        lines.append(f"  readonly {field.name}: {typescript_type(hints[field.name])};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def render() -> str:
    """The whole generated file."""
    names = sorted(name for name in _TYPES if name != "Column")
    request = " | ".join(typescript_type(argument) for argument in typing.get_args(values.Request))
    parts = [_HEADER, _COLUMN]
    parts += [_interface(_TYPES[name]) for name in names]
    parts.append(f"/** What a client may ask a world to do (POST /quote, POST /request). */\n"
                 f"export type Request = {request};\n")
    parts.append("/** Every tagged value the wire carries. */\n"
                 "export type Value = Column | " + " | ".join(names) + ";\n")
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help=f"rewrite {TARGET.name}")
    args = parser.parse_args(argv)
    text = render()
    if args.write:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(text, encoding="utf-8", newline="\n")
    else:
        print(text, end="")


if __name__ == "__main__":
    main()
